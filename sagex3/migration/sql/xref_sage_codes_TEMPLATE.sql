-- xref_sage_codes.sql   (version 3)
--
-- The real cross-reference between the Access codes and the Sage codes.
--
-- migration.XREF_BPC and XREF_BPS hold a numbering that was never used - CUS1001,
-- SUP1001. The codes actually loaded are derived from the name: AB WORLD FOODS became
-- ABW100, 2020 VISUALS LTD became VIS500, Hafele U.K. Ltd became HAF500. Those codes
-- exist only in the two load files, so they are brought in here from the files and
-- matched back to Access on the name.
--
-- WHAT CHANGED IN VERSION 2
-- Version 1 joined on LEFT(name, 35) alone and placed 621 of 623 suppliers but only
-- 194 of 217 customers. The 23 customers it missed showed why: the load files had the
-- NAMES cleansed too, not just the codes. Ampersands and brackets were taken out -
-- "MARKS & SPENCER DC" became "MARKS  SPENCER DC", "ADIDAS (UK) LIMITED" became
-- "ADIDAS UK LIMITED". And the truncation happened BEFORE that, which is why
-- "KEY ELECTRICAL CONTRACTORS & STOREF" is exactly 35 characters and comes out 34.
--
-- So the join now truncates to 35 first, then removes the same characters the
-- cleansing removed - & ( ) ' . , and spaces - from both sides. Tested on the supplier
-- file: 621 of 623, and it also recovers WUX500 which version 1 missed.
--
-- VERSION 3 adds two things version 2 needed:
--   * an exact-name pass ahead of the cleansed one. The load holds both WCP100
--     "WCP ME LIMITED" and WCP101 "WCP.ME LIMITED", and stripping the full stop made
--     them the same name, so both Access accounts landed on one of them.
--   * HCL02 pinned to HOT100. The load file says HOTEL CHOCOLATE LIMITED; the company
--     is Hotel Chocolat. That is a typo in the load file and should be fixed there too.
--
-- Anything still unmatched is reported, not dropped, and MANUAL_PAIRS below is where
-- the handful that will never match on name are pinned by hand.
--
-- Creates: migration.XREF_SAGE_BPS, migration.XREF_SAGE_BPC
-- Run this BEFORE views_v2.sql. Re-runnable.
