-- ===== suppliers: Access code -> Sage code =====
IF OBJECT_ID('migration.XREF_SAGE_BPS') IS NOT NULL DROP TABLE migration.XREF_SAGE_BPS;
SELECT  LTRIM(RTRIM(a.SUCODE)) COLLATE DATABASE_DEFAULT  AS ACCESS_CODE,
        x.SAGE_CODE            COLLATE DATABASE_DEFAULT  AS SAGE_CODE,
        LTRIM(RTRIM(a.SUNAME)) COLLATE DATABASE_DEFAULT  AS ACCESS_NAME,
        x.SAGE_NAME            COLLATE DATABASE_DEFAULT  AS SAGE_NAME,
        x.MATCHED_BY           COLLATE DATABASE_DEFAULT  AS MATCHED_BY
INTO    migration.XREF_SAGE_BPS
FROM    dbo.PL_ACCOUNTS a
CROSS APPLY (
    SELECT TOP 1 s.SAGE_CODE, s.SAGE_NAME, m.MATCHED_BY
    FROM (SELECT 1 AS pri, 'manual' AS MATCHED_BY
          UNION ALL SELECT 2, 'exact name'
          UNION ALL SELECT 3, 'cleansed name') m
    JOIN migration.SAGE_BPS_CODES s
      ON (m.pri = 1 AND s.SAGE_CODE COLLATE DATABASE_DEFAULT IN
             (SELECT p.SAGE_CODE COLLATE DATABASE_DEFAULT FROM migration.XREF_MANUAL_PAIRS p
               WHERE p.KIND = 'supplier'
                 AND p.ACCESS_CODE COLLATE DATABASE_DEFAULT = LTRIM(RTRIM(a.SUCODE)) COLLATE DATABASE_DEFAULT))
       OR (m.pri = 2 AND UPPER(LTRIM(RTRIM(a.SUNAME))) COLLATE DATABASE_DEFAULT
                     = UPPER(LTRIM(RTRIM(s.SAGE_NAME))) COLLATE DATABASE_DEFAULT)
       OR (m.pri = 3 AND REPLACE(REPLACE(REPLACE(REPLACE(REPLACE(REPLACE(REPLACE(LEFT(UPPER(LTRIM(RTRIM(a.SUNAME))), 35), '&', ''), '(', ''), ')', ''), '''', ''), '.', ''), ',', ''), ' ', '') COLLATE DATABASE_DEFAULT
                       = REPLACE(REPLACE(REPLACE(REPLACE(REPLACE(REPLACE(REPLACE(UPPER(LTRIM(RTRIM(s.SAGE_NAME))), '&', ''), '(', ''), ')', ''), '''', ''), '.', ''), ',', ''), ' ', '') COLLATE DATABASE_DEFAULT)
    ORDER BY m.pri
) x;
CREATE UNIQUE CLUSTERED INDEX ix_xsbps ON migration.XREF_SAGE_BPS(ACCESS_CODE);
GO

