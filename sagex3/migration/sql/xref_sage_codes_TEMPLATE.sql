-- ===== 1. Did it work? =====
SELECT 'suppliers' AS kind,
       (SELECT COUNT(*) FROM migration.SAGE_BPS_CODES) AS sage_codes,
       (SELECT COUNT(DISTINCT SAGE_CODE) FROM migration.XREF_SAGE_BPS) AS sage_codes_reached,
       (SELECT COUNT(*) FROM migration.XREF_SAGE_BPS) AS access_codes_mapped
UNION ALL
SELECT 'customers',
       (SELECT COUNT(*) FROM migration.SAGE_BPC_CODES),
       (SELECT COUNT(DISTINCT SAGE_CODE) FROM migration.XREF_SAGE_BPC),
       (SELECT COUNT(*) FROM migration.XREF_SAGE_BPC);

-- ===== 2. Sage accounts still unplaced, with the nearest Access names beside them =====
-- Six characters of the stripped name is enough to put a candidate in front of you
-- without pretending the machine can decide.
WITH unplaced AS (
    SELECT 'supplier' AS kind, s.SAGE_CODE, s.SAGE_NAME
    FROM migration.SAGE_BPS_CODES s
    WHERE NOT EXISTS (SELECT 1 FROM migration.XREF_SAGE_BPS x
                       WHERE x.SAGE_CODE = s.SAGE_CODE COLLATE DATABASE_DEFAULT)
    UNION ALL
    SELECT 'customer', s.SAGE_CODE, s.SAGE_NAME
    FROM migration.SAGE_BPC_CODES s
    WHERE NOT EXISTS (SELECT 1 FROM migration.XREF_SAGE_BPC x
                       WHERE x.SAGE_CODE = s.SAGE_CODE COLLATE DATABASE_DEFAULT)
)
SELECT u.kind, u.SAGE_CODE, u.SAGE_NAME,
       c.access_code AS nearest_access_code, c.access_name AS nearest_access_name
FROM unplaced u
OUTER APPLY (
    SELECT TOP 3 LTRIM(RTRIM(a.SUCODE)) AS access_code, LEFT(LTRIM(RTRIM(a.SUNAME)), 40) AS access_name
    FROM dbo.PL_ACCOUNTS a
    WHERE u.kind = 'supplier'
      AND LEFT(REPLACE(REPLACE(REPLACE(REPLACE(REPLACE(REPLACE(REPLACE(UPPER(LTRIM(RTRIM(a.SUNAME))), '&', ''), '(', ''), ')', ''), '''', ''), '.', ''), ',', ''), ' ', ''), 6) COLLATE DATABASE_DEFAULT
        = LEFT(REPLACE(REPLACE(REPLACE(REPLACE(REPLACE(REPLACE(REPLACE(UPPER(LTRIM(RTRIM(u.SAGE_NAME))), '&', ''), '(', ''), ')', ''), '''', ''), '.', ''), ',', ''), ' ', ''), 6) COLLATE DATABASE_DEFAULT
    UNION ALL
    SELECT TOP 3 LTRIM(RTRIM(a.CUCODE)), LEFT(LTRIM(RTRIM(a.CUNAME)), 40)
    FROM dbo.SL_ACCOUNTS a
    WHERE u.kind = 'customer'
      AND LEFT(REPLACE(REPLACE(REPLACE(REPLACE(REPLACE(REPLACE(REPLACE(UPPER(LTRIM(RTRIM(a.CUNAME))), '&', ''), '(', ''), ')', ''), '''', ''), '.', ''), ',', ''), ' ', ''), 6) COLLATE DATABASE_DEFAULT
        = LEFT(REPLACE(REPLACE(REPLACE(REPLACE(REPLACE(REPLACE(REPLACE(UPPER(LTRIM(RTRIM(u.SAGE_NAME))), '&', ''), '(', ''), ')', ''), '''', ''), '.', ''), ',', ''), ' ', ''), 6) COLLATE DATABASE_DEFAULT
) c
ORDER BY u.kind, u.SAGE_CODE;

-- ===== 3. The money that still cannot be placed =====
SELECT 'customer open items' AS ledger, COUNT(*) AS items, CAST(SUM(ABS(t.ST_UNALLOCATED)) AS decimal(18,2)) AS gbp
FROM dbo.SL_TRANSACTIONS t
LEFT JOIN migration.XREF_SAGE_BPC x ON x.ACCESS_CODE = LTRIM(RTRIM(t.ST_COPYCUST)) COLLATE DATABASE_DEFAULT
WHERE t.ST_UNALLOCATED <> 0 AND x.SAGE_CODE IS NULL
UNION ALL
SELECT 'supplier open items', COUNT(*), CAST(SUM(ABS(t.PT_UNALLOCATED)) AS decimal(18,2))
FROM dbo.PL_TRANSACTIONS t
LEFT JOIN migration.XREF_SAGE_BPS x ON x.ACCESS_CODE = LTRIM(RTRIM(t.PT_COPYSUPP)) COLLATE DATABASE_DEFAULT
WHERE t.PT_UNALLOCATED <> 0 AND x.SAGE_CODE IS NULL;

-- ===== 4. And whose. This is the go-live list: accounts that need creating in X3 =====
SELECT 'supplier' AS kind, LTRIM(RTRIM(t.PT_COPYSUPP)) AS access_code,
       LEFT(LTRIM(RTRIM(a.SUNAME)), 40) AS name, COUNT(*) AS open_items,
       CAST(SUM(ABS(t.PT_UNALLOCATED)) AS decimal(18,2)) AS gbp
FROM dbo.PL_TRANSACTIONS t
LEFT JOIN migration.XREF_SAGE_BPS x ON x.ACCESS_CODE = LTRIM(RTRIM(t.PT_COPYSUPP)) COLLATE DATABASE_DEFAULT
LEFT JOIN dbo.PL_ACCOUNTS a ON LTRIM(RTRIM(a.SUCODE)) COLLATE DATABASE_DEFAULT = LTRIM(RTRIM(t.PT_COPYSUPP)) COLLATE DATABASE_DEFAULT
WHERE t.PT_UNALLOCATED <> 0 AND x.SAGE_CODE IS NULL
GROUP BY LTRIM(RTRIM(t.PT_COPYSUPP)), LEFT(LTRIM(RTRIM(a.SUNAME)), 40)
ORDER BY gbp DESC;

SELECT 'customer' AS kind, LTRIM(RTRIM(t.ST_COPYCUST)) AS access_code,
       LEFT(LTRIM(RTRIM(a.CUNAME)), 40) AS name, COUNT(*) AS open_items,
       CAST(SUM(ABS(t.ST_UNALLOCATED)) AS decimal(18,2)) AS gbp
FROM dbo.SL_TRANSACTIONS t
LEFT JOIN migration.XREF_SAGE_BPC x ON x.ACCESS_CODE = LTRIM(RTRIM(t.ST_COPYCUST)) COLLATE DATABASE_DEFAULT
LEFT JOIN dbo.SL_ACCOUNTS a ON LTRIM(RTRIM(a.CUCODE)) COLLATE DATABASE_DEFAULT = LTRIM(RTRIM(t.ST_COPYCUST)) COLLATE DATABASE_DEFAULT
WHERE t.ST_UNALLOCATED <> 0 AND x.SAGE_CODE IS NULL
GROUP BY LTRIM(RTRIM(t.ST_COPYCUST)), LEFT(LTRIM(RTRIM(a.CUNAME)), 40)
ORDER BY gbp DESC;
GO
